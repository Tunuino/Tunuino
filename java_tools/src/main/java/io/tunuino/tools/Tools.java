package io.tunuino.tools;

import io.tunuino.calibration.CalibrationMap;
import io.tunuino.datalog.CsvLogReader;
import io.tunuino.datalog.CsvLogWriter;
import io.tunuino.datalog.LogSample;
import io.tunuino.protocol.DeviceIdentity;
import io.tunuino.protocol.IdentityClient;
import io.tunuino.protocol.LiveDataClient;
import io.tunuino.transport.PacketSession;
import io.tunuino.transport.ProcessSerialChannel;
import java.io.IOException;
import java.io.PrintStream;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/** Offline developer utilities using the same validated formats and clients as the Console. */
public final class Tools {
    private Tools() {}
    private static final String HELP = "Tunuino tools:\n"
        + "  bin2header input.bin output.h symbol\n  log-summary datalog.csv\n"
        + "  map-export input.tnmap output.csv\n  map-import input.csv output.tnmap\n"
        + "  simulate executable simulated-output.csv count [proteus|uaefi] [normal|stall|sensor-loss|wrap]\n";

    public static void main(String[] args) { System.exit(run(args, System.out, System.err)); }

    public static int run(String[] args, PrintStream out, PrintStream error) {
        try {
            if (args.length == 0 || args[0].equals("--help")) { out.print(HELP); return 0; }
            switch (args[0]) {
                case "bin2header" -> { require(args,4); bin2header(Path.of(args[1]), Path.of(args[2]), args[3]); }
                case "log-summary" -> {
                    require(args,2); var samples = CsvLogReader.read(Path.of(args[1]));
                    double min = samples.stream().mapToDouble(LogSample::rpm).min().orElseThrow();
                    double max = samples.stream().mapToDouble(LogSample::rpm).max().orElseThrow();
                    out.printf(Locale.ROOT,"{\"samples\":%d,\"duration_ms\":%d,\"rpm_min\":%.3f,\"rpm_max\":%.3f}%n",
                        samples.size(),samples.get(samples.size()-1).timeMs()-samples.get(0).timeMs(),min,max);
                }
                case "map-export" -> { require(args,3); exportMap(Path.of(args[1]),Path.of(args[2])); }
                case "map-import" -> { require(args,3); importMap(Path.of(args[1]),Path.of(args[2])); }
                case "simulate" -> {
                    if (args.length < 4 || args.length > 6) throw new IllegalArgumentException(HELP);
                    simulate(Path.of(args[1]),Path.of(args[2]),Integer.parseInt(args[3]),
                        args.length >= 5 ? args[4] : "proteus", args.length == 6 ? args[5] : "normal");
                }
                default -> throw new IllegalArgumentException(HELP);
            }
            return 0;
        } catch (IOException | IllegalArgumentException errorValue) {
            error.println("Tunuino: " + errorValue.getMessage()); return 2;
        }
    }

    private static void require(String[] args, int count) {
        if (args.length != count) throw new IllegalArgumentException(HELP);
    }

    public static void bin2header(Path input, Path output, String symbol) throws IOException {
        if (!symbol.matches("[a-zA-Z][a-zA-Z0-9_]{0,63}") || List.of("auto","break","case","char","const",
                "continue","default","do","double","else","enum","extern","float","for","goto","if","inline",
                "int","long","register","restrict","return","short","signed","sizeof","static","struct","switch",
                "typedef","union","unsigned","void","volatile","while").contains(symbol)) {
            throw new IllegalArgumentException("Invalid C symbol");
        }
        if (Files.size(input) < 1 || Files.size(input) > 512 * 1024) throw new IOException("Binary size must be 1..524288 bytes");
        byte[] bytes = Files.readAllBytes(input);
        String guard = "TUNUINO_EMBEDDED_" + symbol.toUpperCase(Locale.ROOT) + "_H";
        StringBuilder result = new StringBuilder("/* Generated by Tunuino bin2header. */\n#ifndef " + guard + "\n#define " + guard
            + "\nstatic const unsigned char " + symbol + "[] = {\n");
        for (int i=0; i<bytes.length; i++) {
            if (i%12 == 0) result.append("    ");
            result.append(String.format(Locale.ROOT,"0x%02x,",bytes[i]&255));
            result.append(i%12 == 11 || i+1 == bytes.length ? '\n' : ' ');
        }
        result.append("};\nstatic const unsigned long ").append(symbol).append("_size = ").append(bytes.length).append("UL;\n#endif\n");
        Files.writeString(output,result,StandardCharsets.US_ASCII,StandardOpenOption.CREATE_NEW);
    }

    public static void exportMap(Path input, Path output) throws IOException {
        CalibrationMap map = CalibrationMap.read(input);
        StringBuilder text = new StringBuilder("TUNUINO_MAP_CSV,1," + map.kind().name() + "\nmap_kpa/rpm");
        for (int col=0; col<map.columns(); col++) text.append(',').append(map.rpmAt(col));
        text.append('\n');
        for (int row=0; row<map.rows(); row++) {
            text.append(BigDecimal.valueOf(map.loadKpaAt(row)).toPlainString());
            for (int col=0; col<map.columns(); col++) text.append(',').append(BigDecimal.valueOf(map.cell(row,col)).toPlainString());
            text.append('\n');
        }
        Files.writeString(output,text,StandardCharsets.US_ASCII,StandardOpenOption.CREATE_NEW);
    }

    private static int scaled(String value) {
        if (!value.matches("[+-]?[0-9]+(?:\\.[0-9]{1,3})?")) throw new IllegalArgumentException("Use exact decimal values with up to three places");
        try { return new BigDecimal(value).movePointRight(3).intValueExact(); }
        catch (ArithmeticException error) { throw new IllegalArgumentException("Map value out of range",error); }
    }

    public static void importMap(Path input, Path output) throws IOException {
        if (Files.size(input) > 65536) throw new IOException("Map CSV is too large");
        List<String> lines = Files.readAllLines(input,StandardCharsets.US_ASCII);
        if (lines.size() < 4 || lines.size() > 34) throw new IOException("Map CSV needs 2..32 load rows");
        String[] heading = lines.get(0).split(",",-1), axis = lines.get(1).split(",",-1);
        if (heading.length != 3 || !heading[0].equals("TUNUINO_MAP_CSV") || !heading[1].equals("1")
                || !axis[0].equals("map_kpa/rpm") || axis.length < 3 || axis.length > 33) throw new IOException("Invalid map CSV header");
        int[] rpm = new int[axis.length-1], load = new int[lines.size()-2];
        for (int i=0; i<rpm.length; i++) rpm[i] = Integer.parseInt(axis[i+1]);
        int[][] cells = new int[load.length][rpm.length];
        for (int row=0; row<load.length; row++) {
            String[] values = lines.get(row+2).split(",",-1);
            if (values.length != axis.length) throw new IOException("Inconsistent map CSV columns");
            load[row] = scaled(values[0]);
            for (int col=0; col<rpm.length; col++) cells[row][col] = scaled(values[col+1]);
        }
        new CalibrationMap(CalibrationMap.Kind.valueOf(heading[2]),rpm,load,cells).writeNew(output);
    }

    public static void simulate(Path executable, Path output, int count, String family, String scenario) throws IOException {
        if (count < 1 || count > 10000 || !output.getFileName().toString().startsWith("simulated-")) {
            throw new IllegalArgumentException("Use simulated-*.csv and 1..10000 samples");
        }
        Path provenance = output.resolveSibling(output.getFileName()+".provenance.json");
        if (Files.exists(output) || Files.exists(provenance)) throw new IOException("Simulation output already exists");
        var samples = new ArrayList<LogSample>();
        try (var channel = ProcessSerialChannel.simulator(executable,family,scenario); var session = new PacketSession(channel)) {
            DeviceIdentity.Family expected = family.equals("proteus") ? DeviceIdentity.Family.PROTEUS : DeviceIdentity.Family.UAEFI;
            DeviceIdentity identity = IdentityClient.identify(session,expected,Duration.ofSeconds(2));
            if (!identity.uid().equals("53494d554c41544f52303031")) throw new IOException("Not a Tunuino simulator identity");
            for (int attempts=0; attempts < count*5+20 && samples.size()<count; attempts++) {
                LiveDataClient.read(session,identity,Duration.ofSeconds(2)).ifPresent(samples::add);
            }
            if (samples.size() != count) throw new IOException("Simulator did not produce enough valid samples");
        }
        String metadata = "{\"synthetic\":true,\"physical_ecu\":false,\"family\":\"" + family
            + "\",\"scenario\":\"" + scenario + "\",\"samples\":" + count + "}\n";
        Files.writeString(provenance,metadata,StandardCharsets.US_ASCII,StandardOpenOption.CREATE_NEW);
        try (var writer = new CsvLogWriter(output)) { for (LogSample sample : samples) writer.append(sample); }
        catch (IOException error) { if (!Files.exists(output)) Files.deleteIfExists(provenance); throw error; }
    }
}
