#!/usr/bin/env python3
"""Generate the F427 input/calibration profile, retaining the legacy USB definition."""
import argparse
import configparser
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent
SIGNATURE='Tunuino Proteus v0.7 F427 IO v1'
INI_NAME='tunuino_proteus_v07_f427_io.ini'
OUTPUT_BYTES=100


def render():
    lines=['; Copyright (c) 2026 Tunuino. Generated by generate_io.py.',
        '; Physical input/calibration bench. No actuator commands or engine control.',
        '; Disabled/unavailable calibrated channels evaluate to NaN, not measurements.',
        'enable2ndByteCanID = false', '', '[TunerStudio]',
        '    iniSpecVersion = 3.51', '    iniVersion = 2', f'    signature = {json.dumps(SIGNATURE)}',
        '    queryCommand = "S"', '    versionInfo = "V"', '    defaultRuntimeRecordPerSec = 5', '',
        '[Constants]', '    messageEnvelopeFormat = msEnvelope_1.0', '    endianness = big',
        '    nPages = 3', '    pageSize = 256, 160, 160',
        '    pageIdentifier = "\\x00\\x01", "\\x00\\x02", "\\x00\\x03"',
        '    pageReadCommand = "r%2i%2o%2c", "r%2i%2o%2c", "r%2i%2o%2c"',
        '    pageValueWrite = "w%2i%2o%2c%v", "w%2i%2o%2c%v", "w%2i%2o%2c%v"',
        '    pageChunkWrite = "w%2i%2o%2c%v", "w%2i%2o%2c%v", "w%2i%2o%2c%v"',
        '    burnCommand = "b%2i", "b%2i", "b%2i"',
        '    crc32CheckCommand = "k%2i", "k%2i", "k%2i"',
        '    blockingFactor = 64', '    blockReadTimeout = 6000',
        '    interWriteDelay = 0', '    page = 1',
        '    configLayout = scalar, U16, 0, "", 1, 0, 1, 1, 0',
        '    triggerEnabled = bits, U08, 2, [0:0], "Disabled", "Enabled"',
        '    triggerTeeth = scalar, U08, 3, "teeth", 1, 0, 4, 120, 0',
        '    triggerMissing = scalar, U08, 4, "teeth", 1, 0, 1, 59, 0']
    choices='"Disabled", '+', '.join(f'"AV{i}"' for i in range(1,12))
    lines += [f'    mapInput = bits, U08, 6, [0:3], {choices}',
              f'    lambdaInput = bits, U08, 7, [0:3], {choices}',
              '    coolantInput = bits, U08, 8, [0:2], "Disabled", "AT1", "AT2", "AT3", "AT4"']
    fields=[('mapRawLow','U16',10,'ADC',1,0,4095,0),('mapRawHigh','U16',12,'ADC',1,1,4095,0),
        ('mapLow','U16',14,'kPa',0.01,0,500,2),('mapHigh','U16',16,'kPa',0.01,0,500,2),
        ('lambdaRawLow','U16',18,'ADC',1,0,4095,0),('lambdaRawHigh','U16',20,'ADC',1,1,4095,0),
        ('lambdaLow','U16',22,'lambda',0.001,0,5,3),('lambdaHigh','U16',24,'lambda',0.001,0,5,3),
        ('coolantCount','U08',26,'',1,3,3,0),('maximumRpm','U16',96,'rpm',1,1000,20000,0),
        ('adcReference','U16',100,'mV',1,2800,3600,0)]
    for name,kind,offset,unit,scale,minimum,maximum,decimals in fields:
        lines.append(f'    {name} = scalar, {kind}, {offset}, "{unit}", {scale}, 0, {minimum}, {maximum}, {decimals}')
    lines += ['    coolantRaw = array, U16, 32, [3], "ADC", 1, 0, 0, 4095, 0',
        '    coolantTemp = array, S16, 64, [3], "C", 0.01, 0, -40, 150, 2']
    for page,prefix,unit,minimum,maximum in [(2,'ve','%',0,300),(3,'ignition','deg BTDC',-90,90)]:
        lines += [f'    page = {page}', f'    {prefix}Rpm = array, U16, 0, [8], "rpm", 1, 0, 0, 20000, 0',
            f'    {prefix}Load = array, U16, 16, [8], "kPa", 0.01, 0, 0, 500, 2',
            f'    {prefix}Cells = array, S16, 32, [8x8], "{unit}", 0.01, 0, {minimum}, {maximum}, 2']
    lines += ['', '[ConstantExtensions]', '    readOnly = configLayout', '    readOnly = coolantCount', '',
        '[OutputChannels]', '    ochGetCommand = "A"', '    ochBlockSize = 100']
    channels=[('protocolRevision','U08',7,'',1),('boardFamily','U08',8,'',1),('mcuSeries','U08',9,'',1),
        ('hardwareRevision','U16',10,'',1),('firmwareMajor','U08',12,'',1),('firmwareMinor','U08',13,'',1),
        ('firmwarePatch','U08',14,'',1),('capabilities','U32',15,'',1),
        ('uidWord1','U32',19,'',1),('uidWord2','U32',23,'',1),('uidWord3','U32',27,'',1),
        ('uptimeSeconds','U32',32,'s',1),('uptimeMillis','U16',36,'ms',1),
        ('validMask','U08',38,'',1),('ioStatus','U08',39,'',1),
        ('rpmValue','U32',40,'rpm',0.001),('mapValue','U32',44,'kPa',0.001),
        ('lambdaValue','U32',48,'lambda',0.000001),('coolantValue','S32',52,'C',0.001),
        ('configGeneration','U32',56,'',1),('adcReferenceMv','U16',92,'mV',1),
        ('triggerTooth','U16',94,'',1),('triggerErrors','U32',96,'',1)]
    for i in range(16):channels.append((f'raw{i+1}','U16',60+2*i,'ADC',1))
    occupied=set(range(7))|{31}
    for name,kind,offset,unit,scale in channels:
        span=set(range(offset,offset+{'U08':1,'U16':2,'U32':4,'S32':4}[kind]))
        if occupied&span or max(span)>=100:raise ValueError('Overlapping IO channel')
        occupied|=span
        lines.append(f'    {name} = scalar, {kind}, {offset}, "{unit}", {scale}, 0')
    if occupied!=set(range(100)):raise ValueError('Incomplete IO runtime layout')
    lines.append('    time = { uptimeSeconds + uptimeMillis / 1000.0 }, "s"')
    for name,mask,unit in [('rpm',1,'rpm'),('map',2,'kPa'),('lambda',4,'lambda'),('coolant',8,'C')]:
        lines.append(f'    {name} = {{ (validMask & {mask}) != 0 ? {name}Value : (0.0 / 0.0) }}, "{unit}"')
    for i in range(16):
        lines.append(f'    adc{i+1} = {{ (ioStatus & 1) != 0 ? raw{i+1} * adcReferenceMv / 4095000.0 : (0.0 / 0.0) }}, "V"')
    lines += ['', '[CurveEditor]', '    curve = coolantCurve, "Coolant calibration: measured ADC / temperature"',
        '        columnLabel = "ADC", "C"', '        xAxis = 0, 4095, 3', '        yAxis = -40, 150, 10',
        '        xBins = coolantRaw, "ADC"', '        yBins = coolantTemp, "C"', '        showTextValues = true', '', '[TableEditor]']
    for page,prefix,title in [(2,'ve','VE calibration - stored only'),(3,'ignition','Ignition calibration - stored only')]:
        lines += [f'    table = {prefix}Table, {prefix}Map, "{title}", {page}',f'        xBins = {prefix}Rpm, rpm',
            f'        yBins = {prefix}Load, map',f'        zBins = {prefix}Cells','        gridOrient = 250, 0, 340']
    lines += ['', '[GaugeConfigurations]', '    gaugeCategory = "Tunuino IO bench"',
        '    rpmGauge = rpm, "RPM", "rpm", 0, 12000, 0, 0, 10000, 12000, 0, 0',
        '    mapGauge = map, "MAP", "kPa", 0, 300, 0, 0, 250, 300, 2, 2',
        '    lambdaGauge = lambda, "Lambda", "lambda", 0.5, 1.5, 0.6, 0.7, 1.3, 1.4, 3, 3',
        '    coolantGauge = coolant, "Coolant", "C", -40, 150, -40, -30, 120, 140, 1, 1',
        '    uptimeGauge = time, "ECU uptime", "s", 0, 3600, 0, 0, 3600, 3600, 1, 1',
        '    validityGauge = validMask, "Sensor validity mask", "", 0, 15, 0, 0, 15, 15, 0, 0']
    labels=[f'AV{i}' for i in range(1,12)]+['12V divided (MCU)']+[f'AT{i}' for i in range(1,5)]
    for i,label in enumerate(labels):
        lines.append(f'    adc{i+1}Gauge = adc{i+1}, "{label} ADC", "V", 0, 3.6, 0, 0, 3.5, 3.6, 3, 3')
    lines += ['', '[FrontPage]']
    for i,gauge in enumerate(['rpmGauge','mapGauge','lambdaGauge','coolantGauge','uptimeGauge','validityGauge','adc1Gauge','adc13Gauge'],1):lines.append(f'    gauge{i} = {gauge}')
    lines += ['', '[Menu]', '    menuDialog = main', '    menu = "Tunuino"',
        '        subMenu = inputSetup, "Inputs and wheel"', '        subMenu = mapCalibration, "MAP calibration"',
        '        subMenu = lambdaCalibration, "Lambda calibration"', '        subMenu = coolantCurve, "Coolant curve"',
        '        subMenu = rawInputs, "Raw analog inputs"', '        subMenu = veTable, "VE table"',
        '        subMenu = ignitionTable, "Ignition table"', '', '[UiDialogs]',
        '    dialog = inputSetup, "Tunuino input acquisition"',
        '        field = "Input/calibration bench. No engine outputs are configured."',
        '        field = "Use measured calibration data before selecting sensor inputs."',
        '        field = "Crank PE7, cam PE8, rising edge, missing-tooth wheel."']
    for label,field in [('Acquisition','triggerEnabled'),('Wheel slots including missing','triggerTeeth'),('Missing teeth','triggerMissing'),
        ('Maximum RPM','maximumRpm'),('MAP channel','mapInput'),('Lambda channel','lambdaInput'),('Coolant channel','coolantInput'),('ADC reference (measured)','adcReference')]:
        lines.append(f'        field = "{label}", {field}')
    for name,prefix,title in [('mapCalibration','map','MAP sensor'),('lambdaCalibration','lambda','Wideband analog output')]:
        lines += [f'    dialog = {name}, "{title} calibration"', '        field = "Use ADC counts measured on this ECU and values from the sensor/controller specification."']
        for label,suffix in [('Low ADC','RawLow'),('High ADC','RawHigh'),('Value at low ADC','Low'),('Value at high ADC','High')]:lines.append(f'        field = "{label}", {prefix}{suffix}')
    lines += ['    dialog = rawInputs, "Tunuino ADC inputs"',
        '        field = "Voltages at MCU ADC pins. External divider ratios are not applied."']
    for i in range(16):lines.append(f'        gauge = adc{i+1}Gauge')
    lines += ['', '[Datalog]']
    for name,label in [('time','Time'),('rpm','RPM'),('map','MAP kPa'),('lambda','Lambda'),('coolant','Coolant C'),
        ('validMask','Sensor validity'),('ioStatus','IO status'),('triggerErrors','Trigger errors')]:lines.append(f'    entry = {name}, "{label}", float, "%.3f"')
    for i,label in enumerate(labels):lines.append(f'    entry = adc{i+1}, "{label} ADC V", float, "%.3f"')
    content='\n'.join(lines)+'\n'
    parser=configparser.ConfigParser(interpolation=None,strict=False);parser.read_string('[General]\n'+content)
    assert parser['OutputChannels'].getint('ochBlockSize')==OUTPUT_BYTES
    return content


def generate(check=False):
    path=HERE/'generated'/INI_NAME;content=render()
    if check:
        if not path.is_file() or path.read_text()!=content:raise SystemExit('Stale IO INI; run generate.py')
    else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content,encoding='ascii')


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true')
    generate(parser.parse_args().check)
