#!/usr/bin/env python3
"""Generate the bench INI and firmware signature header from one checked schema."""
import argparse
import configparser
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def render(schema, template, fragments):
    if not re.fullmatch(r'tunuino_[a-z0-9_]+\.ini', schema['ini_file']):
        raise ValueError('Invalid generated INI filename')
    if (schema['output_bytes'] != 31 or schema['ini_revision'] != 1
            or len(schema['firmware_version']) != 3
            or any(type(v) is not int or not 0 <= v <= 255 for v in schema['firmware_version'])
            or not schema['signature'].isascii() or not 1 <= len(schema['signature']) <= 96
            or not schema['version_label'].isascii()):
        raise ValueError('Unsupported bench layout/version')
    occupied, names = set(range(7)), set()
    lines = ['    ochGetCommand = "A"', '    ochBlockSize = 31',
             '    ; Big-endian identity block after the envelope status byte.']
    widths = {'U08':1, 'U16':2, 'U32':4}
    for channel in schema['channels']:
        name, kind, offset = channel['name'], channel['type'], channel['offset']
        if (not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', name) or name.lower() in names
                or kind not in widths or type(offset) is not int):
            raise ValueError('Invalid or duplicate output channel')
        span = set(range(offset, offset + widths[kind]))
        if offset < 0 or max(span) >= 31 or occupied & span:
            raise ValueError('Output channels overlap or exceed firmware identity')
        occupied |= span; names.add(name.lower())
        lines.append(f'    {name} = scalar, {kind}, {offset}, "", 1, 0')
    if occupied != set(range(31)):
        raise ValueError('Incomplete output channel layout')
    lines.append('    time = { timeNow }, "s"\n')
    replacements = {'SIGNATURE':json.dumps(schema['signature']), 'INI_REVISION':str(schema['ini_revision']),
                    'CHANNELS':'\n'.join(lines), 'GAUGES':fragments['gauges'],
                    'FRONT_PAGE':fragments['front_page'], 'MENU':fragments['menu']}
    ini = '; Generated by firmware/tunerstudio/generate.py; edit schema/template/fragments.\n' + template
    for key, value in replacements.items(): ini = ini.replace('@@' + key + '@@', value)
    if '@@' in ini: raise ValueError('Unresolved INI template marker')
    definition = configparser.ConfigParser(interpolation=None, strict=False)
    definition.read_string('[General]\n' + ini)
    gauges = definition['GaugeConfigurations']
    for name, value in gauges.items():
        if name != 'gaugecategory' and value.split(',')[0].strip().lower() not in names:
            raise ValueError('Gauge references an unknown channel')
    for value in definition['FrontPage'].values():
        if value.lower() not in gauges: raise ValueError('Front page references an unknown gauge')
    major, minor, patch = schema['firmware_version']
    header = ('/* Copyright (c) 2026 Tunuino. Generated by firmware/tunerstudio/generate.py. */\n'
        '#ifndef TUNUINO_BENCH_TUNERSTUDIO_H\n#define TUNUINO_BENCH_TUNERSTUDIO_H\n\n'
        f'#define TUNUINO_TS_SIGNATURE {json.dumps(schema["signature"])}\n'
        f'#define TUNUINO_BENCH_VERSION {json.dumps(schema["version_label"])}\n'
        f'#define TUNUINO_BENCH_MAJOR {major}\n#define TUNUINO_BENCH_MINOR {minor}\n'
        f'#define TUNUINO_BENCH_PATCH {patch}\n\n#endif\n')
    return ini, header


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail on stale generated files without writing')
    args = parser.parse_args()
    schema = json.loads((HERE / 'schema.json').read_text())
    fragments = {key:(HERE / name).read_text() for key, name in {
        'gauges':'gauge_declarations.ini', 'front_page':'main_page_gauges.ini', 'menu':'top_level_menu.ini'}.items()}
    ini, header = render(schema, (HERE / 'tunerstudio.template.ini').read_text(), fragments)
    outputs = {HERE / 'generated' / schema['ini_file']:ini,
               ROOT / 'firmware/include/tunuino/bench_tunerstudio.h':header}
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content, encoding='ascii')
    if stale: raise SystemExit('Stale definitions; run generate.py: ' + ', '.join(stale))
    print('TunerStudio generated definitions verified.' if args.check else 'Generated INI and matching firmware signature header.')


if __name__ == '__main__': main()
